# apps/api/deleted_insights.py

import os
import json
import time
import datetime as dt
import logging
from typing import Dict, Any, List

import replicate

# Match paths used in admin_dashboard.py
QUEUE_DIR = "/app/post_queue"
DELETED_DIR = os.path.join(QUEUE_DIR, "_deleted")
LOG_DIR = "/app/logs"
DELETED_INSIGHTS_PATH = os.path.join(LOG_DIR, "deleted_insights.json")

REPLICATE_API_TOKEN = os.getenv("REPLICATE_API_TOKEN", "")
REPLICATE_LLM = os.getenv("REPLICATE_LLM", "meta/meta-llama-3-8b-instruct")

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] [UTC deleted_insights] %(message)s",
)
logging.Formatter.converter = time.gmtime
log = logging.getLogger(__name__)


def load_delete_feedback() -> Dict[str, Dict[str, Any]]:
    """
    Load the latest delete feedback per file_name from admin_delete_feedback.log.

    Each line looks like:
      {
        "post_id": "...",
        "file_name": "2025....json",
        "rating": 2,
        "note": "too stiff",
        "caption_score": 3,
        "image_score": 1,
        "issue_type": "image",
        "ts": "2025-12-07T..."
      }
    """
    feedback: Dict[str, Dict[str, Any]] = {}
    path = os.path.join(LOG_DIR, "admin_delete_feedback.log")
    if not os.path.exists(path):
        return feedback

    try:
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                except Exception:
                    continue
                fname = obj.get("file_name")
                if not fname:
                    continue

                feedback[str(fname)] = {
                    "rating": obj.get("rating"),
                    "note": obj.get("note"),
                    "caption_score": obj.get("caption_score"),
                    "image_score": obj.get("image_score"),
                    "issue_type": (obj.get("issue_type") or "other").lower(),
                }
    except Exception as e:
        log.warning("Failed to read delete feedback: %s", e)

    return feedback


def load_deleted_posts(limit: int = 50) -> List[Dict[str, Any]]:
    """
    Load up to `limit` deleted posts from QUEUE_DIR/_deleted,
    newest first, including joined rating/note/score/issue_type.
    """
    examples: List[Dict[str, Any]] = []
    if not os.path.exists(DELETED_DIR):
        return examples

    feedback_map = load_delete_feedback()

    files = [
        os.path.join(DELETED_DIR, f)
        for f in os.listdir(DELETED_DIR)
        if f.endswith(".json")
    ]
    files.sort(key=lambda p: os.path.getmtime(p), reverse=True)

    for path in files[:limit]:
        fname = os.path.basename(path)
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            continue

        caption = (data.get("caption") or "").strip()
        category = (data.get("category") or "").strip().lower() or "unknown"
        status = (data.get("status") or "").strip().lower() or "deleted"
        created_at = data.get("created_at")

        fb = feedback_map.get(fname) or {}
        examples.append(
            {
                "file_name": fname,
                "id": data.get("id"),
                "category": category,
                "status": status,
                "caption": caption,
                "created_at": created_at,
                "rating": fb.get("rating"),
                "note": fb.get("note"),
                "caption_score": fb.get("caption_score"),
                "image_score": fb.get("image_score"),
                "issue_type": fb.get("issue_type") or "other",
            }
        )

    return examples


def build_prompt(
    examples: List[Dict[str, Any]],
    issue_counts: Dict[str, int],
    avg_caption_score: float | None,
    avg_image_score: float | None,
) -> str:
    """
    Build a compact, instruction-heavy prompt for the LLM based on
    deleted posts, with explicit focus on:
      - base prompts
      - training data
      - guardrails / code-level tweaks
    """
    total = len(examples)
    img = issue_counts.get("image", 0)
    cap = issue_counts.get("caption", 0)
    both = issue_counts.get("both", 0)
    other = issue_counts.get("other", 0)

    header = [
        "You are auditing deleted social media posts for a local pool-service business in Florida.",
        "Posts were auto-generated by an AI assistant and then deleted by the owner in the admin dashboard.",
        "",
        f"Total deleted samples analyzed: {total}",
        f"Issue-type counts (from structured feedback): image={img}, caption={cap}, both={both}, other={other}.",
    ]

    if avg_caption_score is not None:
        header.append(f"Average caption_score (1–10, higher=better): {avg_caption_score:.2f}.")
    if avg_image_score is not None:
        header.append(f"Average image_score (1–10, higher=better): {avg_image_score:.2f}.")

    header.append(
        "\nEach sample may include:\n"
        "- category (realistic, meme, educational, comedic, confrontational, persuasive, etc.)\n"
        "- caption text\n"
        "- rating (legacy overall)\n"
        "- caption_score (1–10)\n"
        "- image_score (1–10)\n"
        "- issue_type (image / caption / both / other)\n"
        "- note from human (e.g. 'too stiff', 'too salesy', 'image is weird', etc.)\n"
    )

    header.append(
        "Your job is to propose *concrete changes* in three areas:\n"
        "1) CAPTION & TONE: how should prompts / brand-voice logic change?\n"
        "2) IMAGE GENERATION PIPELINE: what should change in prompts, model settings, "
        "   or guardrails to reduce image-driven deletions?\n"
        "3) TRAINING DATA & BASE CODE: specific suggestions for improving training data files, "
        "   category balance, and high-impact code modules (e.g. image_prompt_manager.py, "
        "   poster.py, admin feedback flow). Focus on *what* to change, not exact code.\n\n"
        "Use short, concrete bullet points, no long essays."
    )

    header.append("\nDeleted post samples:\n")

    lines: List[str] = ["\n".join(header)]

    for i, ex in enumerate(examples, start=1):
        cap_text = ex.get("caption") or ""
        if len(cap_text) > 320:
            cap_text = cap_text[:317] + "..."

        line = (
            f"{i}. category={ex.get('category')}, "
            f"issue_type={ex.get('issue_type')}, "
            f"caption_score={ex.get('caption_score')}, "
            f"image_score={ex.get('image_score')}, "
            f"rating={ex.get('rating')}, "
            f"note={ex.get('note')!r}, "
            f"caption={cap_text!r}"
        )
        lines.append(line)

    lines.append(
        "\nNow output 3 clearly labeled sections with bullet points only:\n"
        "A) Caption & Tone\n"
        "B) Image Generation & Prompts\n"
        "C) Training Data & Base-Code / Guardrail Adjustments\n"
        "Do not output JSON."
    )

    return "\n".join(lines)


def call_llm(prompt: str) -> str:
    """
    Call the Replicate LLM and return plain text.
    If anything fails, return an empty string.
    """
    if not REPLICATE_API_TOKEN:
        log.warning("No REPLICATE_API_TOKEN set; skipping LLM call.")
        return ""

    try:
        output = replicate.run(
            REPLICATE_LLM,
            input={"prompt": prompt},
        )
        if isinstance(output, str):
            return output.strip()
        text = "".join(str(chunk) for chunk in output)
        return text.strip()
    except Exception as e:
        log.error("LLM call failed: %s", e)
        return ""


def default_no_data_message() -> Dict[str, Any]:
    """
    Default payload when there are no deleted posts or
    the analysis cannot be generated.
    """
    return {
        "generated_at": None,
        "sample_size": 0,
        "used_llm": False,
        "suggestions": (
            "No deleted-post analysis available yet. "
            "Either there are no deleted posts, or the insights job failed to run."
        ),
        "example_categories": [],
        "issue_counts": {"image": 0, "caption": 0, "both": 0, "other": 0},
        "avg_caption_score": None,
        "avg_image_score": None,
    }


def generate_deleted_insights(max_files: int = 50) -> Dict[str, Any]:
    """
    Main worker: load deleted posts, compute stats, call LLM,
    and write deleted_insights.json.
    """
    examples = load_deleted_posts(limit=max_files)
    if not examples:
        payload = default_no_data_message()
    else:
        # aggregate stats
        issue_counts = {"image": 0, "caption": 0, "both": 0, "other": 0}
        caption_scores: List[float] = []
        image_scores: List[float] = []

        for ex in examples:
            t = (ex.get("issue_type") or "other").lower()
            if t not in issue_counts:
                t = "other"
            issue_counts[t] += 1

            cs = ex.get("caption_score")
            if isinstance(cs, (int, float)):
                caption_scores.append(float(cs))

            ims = ex.get("image_score")
            if isinstance(ims, (int, float)):
                image_scores.append(float(ims))

        avg_caption_score = (
            sum(caption_scores) / len(caption_scores) if caption_scores else None
        )
        avg_image_score = (
            sum(image_scores) / len(image_scores) if image_scores else None
        )

        prompt = build_prompt(
            examples,
            issue_counts=issue_counts,
            avg_caption_score=avg_caption_score,
            avg_image_score=avg_image_score,
        )
        analysis = call_llm(prompt)

        categories = sorted(
            {ex.get("category") or "unknown" for ex in examples}
        )

        if analysis:
            payload = {
                "generated_at": dt.datetime.now(dt.timezone.utc).replace(tzinfo=None).isoformat() + "Z",
                "sample_size": len(examples),
                "used_llm": True,
                "suggestions": analysis,
                "example_categories": categories,
                "issue_counts": issue_counts,
                "avg_caption_score": avg_caption_score,
                "avg_image_score": avg_image_score,
            }
        else:
            payload = default_no_data_message()
            payload["sample_size"] = len(examples)
            payload["example_categories"] = categories
            payload["issue_counts"] = issue_counts
            payload["avg_caption_score"] = avg_caption_score
            payload["avg_image_score"] = avg_image_score

    os.makedirs(LOG_DIR, exist_ok=True)
    try:
        with open(DELETED_INSIGHTS_PATH, "w", encoding="utf-8") as f:
            json.dump(payload, f, ensure_ascii=False, indent=2)
    except Exception as e:
        log.error("Failed to write deleted_insights.json: %s", e)

    return payload


def main():
    payload = generate_deleted_insights()
    log.info(
        "Deleted insights generated: sample_size=%s used_llm=%s",
        payload.get("sample_size"),
        payload.get("used_llm"),
    )
    print(json.dumps(payload, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
